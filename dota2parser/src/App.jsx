// --- Per-game / per-series scoring (group stage CSV data) ---
// A player's raw score for one game is paired with their core/support
// teammate (averaged) or used solo for mid, then a series score takes the
// best 2 of up to 3 games (Bo3) and sums them.

const parseCsv = (raw) => {
  const lines = raw.trim().split(/\r?\n/);
  const headers = lines[0].split(',');
  return lines.slice(1).map(line => {
    const values = line.split(',');
    const row = {};
    headers.forEach((header, i) => { row[header] = values[i]; });
    return row;
  });
};

