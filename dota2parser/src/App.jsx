const suffixAppliesToRow = (subtitleKey, row, tormentorMatchIds) => {
  switch (subtitleKey) {
    case 'lost_games': return Number(row.win) === 0;
    case 'clutch': return Number(row.isLastGame) === 1;
    case 'lucky': return row.gametime.slice(-1) === '8';
    case 'total_deaths_from_torm': return tormentorMatchIds.has(row.matchID);
    case 'firstblood_before_10min': return Number(row.first_blood_time) > 600;
    case 'firstblood_before_horn': return Number(row.first_blood_time) < 0;
    case 'games<25min': return Number(row.gametime) < 1500;
    default: return false;
  }
};

const titleAppliesToRow = (titleKey, row) => Number(row[`is_${titleKey}`]) === 1;

const computePlayerGameScore = (row, statSlots, titleKey, subtitleKey, tormentorMatchIds) => {
  let total = 0;
  statSlots.forEach(({ stat, multiplier }) => {
    if (!stat) return;
    const weight = multipliers[stat] ?? 1;
    const raw = toFiniteNumber(row[stat]);
    total += stat === 'deaths'
      ? (1950 - raw * 195) * multiplier
      : raw * weight * multiplier;
  });

  let bonusPercent = 0;
  if (titleKey && titleAppliesToRow(titleKey, row)) bonusPercent += titlesInfo[titleKey]?.percent || 0;
  if (subtitleKey && suffixAppliesToRow(subtitleKey, row, tormentorMatchIds)) bonusPercent += subtitlesInfo[subtitleKey]?.percent || 0;

  return total + (total / 100) * bonusPercent;
};

// Best 2 of up to 3 game scores for one (series, team, position) group,
// pairing core/support teammates (averaged) or using mid solo.
const computeSeriesRoleScore = (key, statSlots, titleKey, subtitleKey, seriesTeamPositionGames, tormentorMatchIds) => {
  const gamesByMatch = seriesTeamPositionGames[key];
  if (!gamesByMatch) return { score: 0, playerNames: [] };

  const gameScores = Object.values(gamesByMatch).map(playerRows => {
    const perPlayerScores = playerRows.map(row => computePlayerGameScore(row, statSlots, titleKey, subtitleKey, tormentorMatchIds));
    return perPlayerScores.reduce((a, b) => a + b, 0) / perPlayerScores.length;
  });

  gameScores.sort((a, b) => b - a);
  const bestTwo = gameScores.slice(0, 2);
  const score = bestTwo.reduce((a, b) => a + b, 0);

  const anyGamePlayers = Object.values(gamesByMatch)[0];
  const playerNames = anyGamePlayers.map(row => row.playerName);

  return { score, playerNames };
};

